//! An 8x10 bitmap font, drawn at whole-pixel scale.
//!
//! Sized and weighted after the text Sega's mid-nineties boards put on screen
//! -- CREDIT, INSERT COIN(S) -- rather than the coarse 5x7 cell of a decade
//! earlier: two-pixel stems, square terminals, and enough height for the
//! letterforms to have shape rather than being suggestions of one.
//!
//! Everything is integer: the glyphs are literal bitmaps and scaling is
//! replication, so the text sits on the framebuffer as hard-edged as the
//! machine's own.

/// Glyph width in pixels, before scaling.
pub const GLYPH_W: usize = 8;
/// Glyph height in pixels, before scaling.
pub const GLYPH_H: usize = 10;
/// Blank columns between glyphs, before scaling.
pub const TRACKING: usize = 1;

